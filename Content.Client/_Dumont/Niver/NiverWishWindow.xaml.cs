using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Dumont.Niver;

[GenerateTypedNameReferences]
public sealed partial class NiverWishWindow : BaseWindow
{
    public event Action<bool>? OnAnswered;

    private static readonly TimeSpan UrgentTime = TimeSpan.FromSeconds(5);

    private readonly TimeSpan _duration;
    private readonly StyleBoxFlat _barStyle = new(Color.FromHex("#f5c542"));
    private TimeSpan _remaining;
    private bool _answered;

    public NiverWishWindow(TimeSpan duration)
    {
        RobustXamlLoader.Load(this);
        Resizable = false;

        _duration = duration;
        _remaining = duration;

        MessageLabel.SetMessage(FormattedMessage.FromMarkupPermissive(Loc.GetString("niver-wish-window-text")));
        TimerBar.ForegroundStyleBoxOverride = _barStyle;
        UpdateTimer();

        WishButton.OnPressed += _ => Answer(true);
        RefuseButton.OnPressed += _ => Answer(false);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_answered)
            return;

        _remaining -= TimeSpan.FromSeconds(args.DeltaSeconds);
        if (_remaining <= TimeSpan.Zero)
        {
            _answered = true;
            base.Close();
            return;
        }

        UpdateTimer();
    }

    public override void Close()
    {
        if (!_answered)
        {
            _answered = true;
            OnAnswered?.Invoke(false);
        }

        base.Close();
    }

    private void Answer(bool wished)
    {
        if (_answered)
            return;

        _answered = true;
        OnAnswered?.Invoke(wished);
        base.Close();
    }

    private void UpdateTimer()
    {
        TimerBar.Value = (float) (_remaining / _duration);
        _barStyle.BackgroundColor = _remaining <= UrgentTime ? Color.FromHex("#d94141") : Color.FromHex("#f5c542");
        TimerLabel.Text = Loc.GetString("niver-wish-window-timer", ("seconds", (int) Math.Ceiling(_remaining.TotalSeconds)));
    }
}
