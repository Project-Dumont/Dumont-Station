using Content.Client.UserInterface.Controls;
using Content.Shared.Notification;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Content.Client._Dumont.UserInterface;

namespace Content.Client.Silicons.Borgs;

[GenerateTypedNameReferences]
public sealed partial class BorgNotificationsMenu : FancyWindow
{
    public List<NotificationMessage> notifications = new List<NotificationMessage>();
    public BorgNotificationsMenu() 
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
    }

    public void UpdateState(List<NotificationMessage> notifs)
    {
        notifications = notifs;
        Notifications.RemoveAllChildren();

        NotificationsView view = new(notifs);
        Notifications.AddChild(view);
    }
}